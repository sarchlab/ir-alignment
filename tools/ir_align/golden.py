"""Computes the reference result by running the kernel's own C/C++ source
natively on the host, on the very same memory image the simulators get.

The kernel source is #included into a generated harness (with its ``main``
renamed), so static helpers, C++ name mangling and polybench macros all work
unchanged and the reference is the source itself rather than a hand-written
re-implementation.
"""

import json
import os
import shutil
import subprocess
from pathlib import Path

from .spec import KernelSpec, to_int32


def _harness_source(spec: KernelSpec) -> str:
  is_cxx = spec.language == "c++"
  init = ",".join(str(v) for v in spec.initial_memory())
  call_args = []
  for arg in spec.args:
    if arg.kind == "array":
      # C: void* converts implicitly to any object pointer, including
      # polybench's `int A[N][M]` parameters. C++: arrays decay to int*.
      call_args.append(f"(int*)(ir_mem + {arg.base})" if is_cxx else f"(void*)(ir_mem + {arg.base})")
    else:
      call_args.append(str(arg.value))
  call = f"{spec.function}({', '.join(call_args)})"
  ret_line = (f"  long long ir_ret = (long long)({call});\n"
              if spec.returns_value else f"  {call};\n  long long ir_ret = 0;\n")
  return f"""/* Generated by ir-alignment. Do not edit. */
#include <stdio.h>
#include <stdint.h>
#define main ir_alignment_original_main
#include "{spec.source}"
#undef main

static int32_t ir_mem[{spec.memory_words}] = {{{init}}};

int main(void) {{
{ret_line}  printf("{{\\"return\\": %lld, \\"memory\\": [", ir_ret);
  for (int i = 0; i < {spec.memory_words}; ++i)
    printf(i ? ",%d" : "%d", (int)ir_mem[i]);
  printf("]}}\\n");
  return 0;
}}
"""


def compute_golden(spec: KernelSpec, out_dir: Path) -> dict:
  spec.require_source()
  out_dir.mkdir(parents=True, exist_ok=True)
  ext = ".cpp" if spec.language == "c++" else ".c"
  harness = out_dir / f"golden_harness{ext}"
  harness.write_text(_harness_source(spec))
  exe = out_dir / "golden"
  if spec.language == "c++":
    cc = os.environ.get("HOST_CXX") or shutil.which("clang++") or "g++"
    std = "-std=c++17"
  else:
    cc = os.environ.get("HOST_CC") or shutil.which("clang") or "gcc"
    std = "-std=gnu11"
  cmd = [cc, std, "-O1", "-w", "-fwrapv", f"-I{spec.source.parent}",
         # polybench: keep arrays on the stack so the unused original main()
         # does not need polybench.c at link time.
         "-DPOLYBENCH_STACK_ARRAYS",
         *spec.cflags, "-o", str(exe), str(harness)]
  proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
  (out_dir / "golden.log").write_text("$ " + " ".join(cmd) + "\n" + proc.stdout)
  if proc.returncode != 0:
    raise RuntimeError(f"golden harness failed to build:\n{proc.stdout[-3000:]}")
  run = subprocess.run([str(exe)], stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
                       timeout=120)
  if run.returncode != 0:
    raise RuntimeError(f"golden harness crashed ({run.returncode}): {run.stderr[-2000:]}")
  result = json.loads(run.stdout.strip().splitlines()[-1])
  result["return"] = to_int32(result["return"])
  result["memory"] = [to_int32(v) for v in result["memory"]]
  return result
